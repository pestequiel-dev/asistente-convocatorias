import { chromium } from "playwright";
const b = await chromium.launch({ headless: true, executablePath: "/Applications/Brave Browser.app/Contents/MacOS/Brave Browser" });
const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
await p.goto("http://127.0.0.1:3100/programa/5", { waitUntil: "networkidle" });
await p.waitForTimeout(800);
const t = await p.evaluate(() => document.body.innerText);
console.log("LEN", t.length);
console.log(t.slice(-1800));
const aside = await p.$$eval(".detail-grid > div:nth-child(2) section", (els) => els.map((e) => e.innerText.slice(0, 120)));
console.log("SIDE SECTIONS:", JSON.stringify(aside, null, 1));
await b.close();
