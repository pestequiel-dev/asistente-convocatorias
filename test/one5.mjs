import { chromium } from "playwright";
const b = await chromium.launch({ headless: true, executablePath: "/Applications/Brave Browser.app/Contents/MacOS/Brave Browser" });
const p = await b.newPage({ viewport: { width: 1440, height: 1300 } });
p.on("request", (r) => { if (r.url().includes("/api/programs/243") && r.method() !== "GET") console.log("REQ", r.method(), r.url().slice(-30), r.postData()?.slice(0, 120)); });
p.on("response", (r) => { if (r.url().includes("/api/programs/243") && r.request().method() !== "GET") console.log("RES", r.status()); });
await p.goto("http://127.0.0.1:3100/programa/243", { waitUntil: "networkidle" });
await p.waitForTimeout(1300);
await p.fill("#notas-gestion", "Prueba de nota unificada " + Date.now());
await p.getByRole("button", { name: /^Guardar$/ }).click();
await p.waitForTimeout(2000);
console.log("events:", await p.evaluate(() => [...document.querySelectorAll(".card")].find((c) => c.innerText.includes("Historial"))?.querySelectorAll("li").length));
await b.close();
