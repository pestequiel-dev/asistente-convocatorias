import { chromium } from "playwright";
const b = await chromium.launch({ headless: true, executablePath: "/Applications/Brave Browser.app/Contents/MacOS/Brave Browser" });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const logs = [];
p.on("console", (m) => { if (m.type() === "error") logs.push(m.text().slice(0, 300)); });
p.on("pageerror", (e) => logs.push("PAGEERROR: " + e.message.slice(0, 300)));
await p.goto("http://127.0.0.1:3100/resumen", { waitUntil: "networkidle" });
await p.waitForTimeout(1200);
console.log(JSON.stringify(logs, null, 1));
await b.close();
