import { chromium } from "playwright";
const b = await chromium.launch({ headless: true, executablePath: "/Applications/Brave Browser.app/Contents/MacOS/Brave Browser" });
const p = await b.newPage({ viewport: { width: 1440, height: 1200 } });
await p.goto("http://127.0.0.1:3100/programa/13", { waitUntil: "networkidle" });
await p.waitForTimeout(1200);
const count = () => p.evaluate(() => [...document.querySelectorAll(".card")].find((c) => c.innerText.includes("Historial"))?.querySelectorAll("li").length ?? -1);
const before = await count();
await p.selectOption("select.select >> nth=0", "reviewing");
await p.waitForTimeout(2000);
const after = await count();
const last = await p.evaluate(() => [...document.querySelectorAll(".card")].find((c) => c.innerText.includes("Historial"))?.querySelector("li")?.innerText.replace(/\n/g, " ").slice(0, 70));
console.log(JSON.stringify({ before, after, last }));
await b.close();
